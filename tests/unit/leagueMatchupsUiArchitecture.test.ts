    expect(lineupFieldBoard).not.toContain('bg-slate-950/64 p-3');
    expect(lineupFieldBoard).toContain('interchangeSpots');
    expect(lineupFieldBoard).toContain('Lineup sideline');
    expect(lineupFieldBoard).toContain('variant="interchange"');
    expect(lineupFieldBoard).not.toContain('border-red-700');
    expect(lineupFieldBoard).not.toContain('bg-slate');
    expect(lineupRosterPool).not.toContain('text-cyan');
    expect(lineupFieldBoard).toContain('radial-gradient');
    expect(lineupFieldBoard).toContain('lg:grid-cols-1');
    expect(lineupFieldBoard).toContain('onDrop');
    expect(lineupFieldBoard).toContain('getDragPlayerId');
    expect(lineupFieldBoard).toContain('selectedPlayerId');
    expect(lineupFieldBoard).toContain('Assign selected player');
    expect(lineupFieldBoard).toContain('Clear');
    expect(lineupFieldBoard).not.toContain('min-h-24');
