    expect(lineupFieldBoard).toContain('SLOT_BAND_GRIDS');
    expect(lineupFieldBoard).toContain('Field builder');
    expect(lineupFieldBoard).toContain('Interchange');
    expect(lineupFieldBoard).toContain('min-h-[1120px]');
